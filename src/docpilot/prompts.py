# ============================================================
# 工具函数：把证据列表拼成提示词里的文本块
# ============================================================
def format_documents(documents: list[dict]) -> str:
    """
    把检索到的证据拼成带编号的文本块。

    之所以要编号 [1] [2]，是因为后面生成答案时要求模型标注引用来源，
    这样才能做到"每句话都能追溯到原文"——这是 RAG 系统可信度的关键。
    """
    if not documents:
        return "（没有检索到任何资料）"

    blocks = []
    for i, doc in enumerate(documents, start=1):
        source = doc.get("source", "未知来源")
        content = doc.get("content", "").strip()
        score = doc.get("score")
        score_text = f"，相关度 {score:.2f}" if isinstance(score, (int, float)) else ""
        blocks.append(f"[{i}] 来源：{source}{score_text}\n内容：{content}")
    return "\n\n".join(blocks)


def format_issues(issues: list[str]) -> str:
    if not issues:
        return "（无明显问题，但按策略仍需人工确认）"
    return "\n".join(f"- {item}" for item in issues)
